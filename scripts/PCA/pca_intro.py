import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler

import os

'''
###############################################################################
##########      Leer archivo e indicar columnas que no se usarán      #########
###############################################################################
'''

## Carpeta donde está el archivo
os.chdir(r"............")

## leer el archivo
df = pd.read_csv("............csv")

df.columns
df.head()

#%%
###############################################################################
###############################################################################
###############################################################################

cols_not = [] # columnas a excluir. Dejar vacío si no hay

###############################################################################
###############################################################################
###############################################################################


#%%

###############################################################################
###############################################################################
###############################################################################

cols_use = [x for x in df.columns if x not in cols_not]

X = df[cols_use]

'''
###############################################################################
##########     Seleccionar número de componentes      #########################
###############################################################################
'''

n_componentes = 3

###############################################################################
###############################################################################
###############################################################################

scaler = StandardScaler()
Z = scaler.fit_transform(X)

Z.shape
np.mean(Z,axis=0)
np.var(Z,axis=0)


# Aplicar PCA
pca = PCA(n_components=n_componentes)
Yk = pca.fit_transform(Z)
    
pca.explained_variance_ratio_.sum()
    
